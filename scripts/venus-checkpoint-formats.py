#!/usr/bin/env python3
"""Generate image-copy block geometry from the vendored Vulkan registry.

Single-plane colour formats only. Depth/stencil aspect packing and PVRTC's
minimum encoded footprint require their own copy rules, so are not admitted.
Uses only Python's standard library. --check verifies the committed output.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET


def patterns(values: set[int]) -> str:
    parts = []
    ordered = sorted(values)
    start = previous = ordered[0]
    for value in ordered[1:] + [None]:
        if value is not None and value == previous + 1:
            previous = value
            continue
        if previous - start >= 2:
            parts.append(f'{start}..={previous}')
        else:
            parts.extend(map(str, range(start, previous + 1)))
        start = previous = value
    return ' | '.join(parts)


def generate(root: Path) -> str:
    tree = ET.parse(root / 'tools/venus-protocol/xmls/vk.xml').getroot()
    numbers = {}
    aliases = {}
    parents = {id(e): int(ext.get('number'))
               for ext in tree.findall('./extensions/extension')
               if ext.get('number')
               for e in ext.findall('.//enum')}
    for e in tree.iter('enum'):
        name = e.get('name', '')
        if not name.startswith('VK_FORMAT_'):
            continue
        if e.get('alias'):
            aliases[name] = e.get('alias')
        elif e.get('value'):
            try:
                numbers[name] = int(e.get('value'), 0)
            except ValueError:
                pass  # Flag expressions are not VkFormat values.
        elif e.get('offset'):
            extension = int(e.get('extnumber') or parents.get(id(e), 0))
            if extension:
                value = 1000000000 + (extension - 1) * 1000 + int(e.get('offset'))
                numbers[name] = -value if e.get('dir') == '-' else value
    for _ in range(len(aliases)):
        unresolved = [(name, target) for name, target in aliases.items() if name not in numbers and target in numbers]
        if not unresolved:
            break
        for name, target in unresolved:
            numbers[name] = numbers[target]

    groups = defaultdict(set)
    for fmt in tree.findall('./formats/format'):
        if fmt.find('plane') is not None or fmt.get('compressed') == 'PVRTC':
            continue
        if any(c.get('name') in ('D', 'S') for c in fmt.findall('component')):
            continue
        name = fmt.get('name')
        if name not in numbers:
            raise ValueError(f'No numeric VkFormat for {name}')
        extent = tuple(map(int, fmt.get('blockExtent', '1,1,1').split(',')))
        size = int(fmt.get('blockSize'))
        if len(extent) != 3 or min(*extent, size) <= 0:
            raise ValueError(f'Invalid format block: {name}')
        groups[(*extent, size)].add(numbers[name])
    lines = [
        '// @generated by scripts/venus-checkpoint-formats.py from tools/venus-protocol/xmls/vk.xml.',
        '// DO NOT EDIT: regenerate with the script, or verify with --check.',
        'use super::Block;',
        'pub(super) fn color_block(format: i32) -> Option<Block> {',
        'let (width, height, depth, bytes) = match format {',
    ]
    for geometry, values in sorted(groups.items()):
        lines.append(patterns(values) + ' => ' + str(geometry) + ',')
    lines.extend(['_ => return None,', '};', 'Some(Block { width, height, depth, bytes })', '}'])
    result = subprocess.run(['rustfmt', '--edition', '2024'], input='\n'.join(lines) + '\n',
                            capture_output=True, text=True, check=True)
    return result.stdout


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    output = root / 'crates/virtio-gpu/src/venus/executor/checkpoint_images/formats.rs'
    expected = generate(root)
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != expected:
            raise SystemExit(f'Stale image-copy formats: run {Path(__file__).name}')
        print('Venus checkpoint format geometry matches vk.xml')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding='utf-8')
        print(f'Generated {output.relative_to(root)}')


if __name__ == '__main__':
    main()
