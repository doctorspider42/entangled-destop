#!/usr/bin/env python3
"""Generates the OpenGL 1.1 marshalling of the XP OpenGL driver (ADR-0013).

Two inputs, both facts rather than code:

  * `icd_table.txt` beside this script: the 336 functions of a Windows ICD's
    dispatch table, in order (read out of XP's opengl32.dll);
  * the Windows SDK's `gl/GL.h`: their prototypes.

and two outputs, both checked in:

  * `gl_stubs.inc` — the guest side, C: one function per table entry that
    packs its arguments into the command buffer;
  * `crates/gl-passthrough/src/calls_gen.rs` — the host side, Rust: what
    each opcode's arguments are, and the call it becomes.

The wire format is one 32-bit word per integer or float argument and two
per double, behind a header word `opcode | words << 16`; the opcode of an
OpenGL 1.1 function is its index in the dispatch table.

Only functions whose every argument is a number are generated here, plus
the fixed-size vector forms (`glVertex3fv`), which the guest turns into
their scalar twins so the host never sees them. Everything that carries a
pointer whose length depends on state — textures, client arrays, queries —
is written by hand in `icd.c` and `exec.rs`; the stubs for those are named
in `HANDWRITTEN` and left out of the generated table.

  python gen.py "<Windows Kits>/Include/<version>/um/gl/GL.h"
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]

SCALAR_WORDS = {
    "GLenum": 1, "GLboolean": 1, "GLbitfield": 1, "GLbyte": 1, "GLshort": 1, "GLint": 1,
    "GLsizei": 1, "GLubyte": 1, "GLushort": 1, "GLuint": 1, "GLfloat": 1, "GLclampf": 1,
    "GLdouble": 2, "GLclampd": 2,
}
FLOATS = {"GLfloat", "GLclampf"}
DOUBLES = {"GLdouble", "GLclampd"}

# Scalar-only functions that are still not a plain call on the host: they
# read client memory through state, return a value, or belong to the
# client. Written by hand on both sides.
HANDWRITTEN = {
    "glDrawArrays", "glArrayElement", "glEnableClientState", "glDisableClientState",
    "glPushClientAttrib", "glPopClientAttrib", "glRenderMode", "glGenLists", "glIsList",
    "glIsEnabled", "glIsTexture", "glGetError", "glFinish", "glFlush", "glDrawBuffer",
    "glReadBuffer", "glPixelStorei", "glPixelStoref",
}

# `glVertex3fv` and its kin: name stem, how many, element type letter.
VECTOR = re.compile(
    r"^gl(Vertex|Color|Normal|TexCoord|RasterPos|Index|EvalCoord)([1-4]?)(b|s|i|f|d|ub|us|ui)v$"
)
LETTER_TYPE = {
    "b": "GLbyte", "s": "GLshort", "i": "GLint", "f": "GLfloat", "d": "GLdouble",
    "ub": "GLubyte", "us": "GLushort", "ui": "GLuint",
}


def prototypes(header):
    text = Path(header).read_text(errors="replace")
    out = {}
    for match in re.finditer(
        r"WINGDIAPI\s+(.+?)\s+APIENTRY\s+(gl\w+)\s*\(([^)]*)\)\s*;", text
    ):
        returns, name, params = match.group(1).strip(), match.group(2), match.group(3).strip()
        args = []
        if params != "void":
            for param in params.split(","):
                param = param.strip()
                pointer = "*" in param
                words = param.replace("*", " ").split()
                kind = [w for w in words if w not in ("const",)][0]
                args.append((kind, words[-1], "const *" if pointer and "const" in words else pointer))
        out[name] = (returns, args)
    return out


def main():
    protos = prototypes(sys.argv[1])
    table = [
        line.strip()
        for line in (HERE / "icd_table.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    assert len(table) == 336, len(table)
    index = {name: i for i, name in enumerate(table)}
    missing = [name for name in table if name not in protos]
    assert not missing, missing

    stubs = [
        "/* Generated by gen.py from icd_table.txt and the SDK's GL.h. Do not edit. */",
        "",
    ]
    calls = []
    generated, vectors, by_hand = [], [], []
    for i, name in enumerate(table):
        returns, args = protos[name]
        signature = ", ".join(
            f"{'const ' if ptr == 'const *' else ''}{kind} {'*' if ptr else ''}{arg}" for kind, arg, ptr in args
        ) or "void"
        vector = VECTOR.match(name)
        if vector and len(args) == 1 and args[0][2]:
            stem, count, letter = vector.groups()
            count = int(count) if count else 1
            twin = f"gl{stem}{count if stem != 'Index' else ''}{letter}"
            if twin in index and twin not in HANDWRITTEN:
                kind = LETTER_TYPE[letter]
                values = ", ".join(f"{args[0][1]}[{n}]" for n in range(count))
                stubs.append(
                    f"static {returns} APIENTRY icd_{name[2:]}({signature})\n"
                    f"{{\n    icd_{twin[2:]}({values});\n}}\n"
                )
                vectors.append(name)
                assert kind
                continue
        scalar = all(not ptr and kind in SCALAR_WORDS for kind, _, ptr in args)
        if not scalar or returns != "void" or name in HANDWRITTEN:
            by_hand.append(name)
            continue
        words = sum(SCALAR_WORDS[kind] for kind, _, _ in args)
        body = [f"    unsigned *entgl_a = entgl_command({i}, {words});"]
        at = 0
        rust_args, rust_types = [], []
        for kind, arg, _ in args:
            if kind in DOUBLES:
                body.append(f"    entgl_put_double(entgl_a + {at}, {arg});")
                rust_args.append(f"crate::f64_at(a, {at})")
                at += 2
            elif kind in FLOATS:
                body.append(f"    entgl_put_float(entgl_a + {at}, {arg});")
                rust_args.append(f"f32::from_bits(a[{at}])")
                at += 1
            else:
                body.append(f"    entgl_a[{at}] = (unsigned){arg};")
                rust_args.append(f"a[{at}] as _")
                at += 1
            rust_types.append(kind)
        if not args:
            body = [f"    (void)entgl_command({i}, 0);"]
        stubs.append(
            f"static void APIENTRY icd_{name[2:]}({signature})\n{{\n" + "\n".join(body) + "\n}\n"
        )
        calls.append((i, name, words, rust_args))
        generated.append(name)

    # The vector forms call their twins, so the twins must come first in the
    # file: declare every stub up front.
    declarations = []
    for name in table:
        returns, args = protos[name]
        signature = ", ".join(
            f"{'const ' if ptr == 'const *' else ''}{kind} {'*' if ptr else ''}{arg}" for kind, arg, ptr in args
        ) or "void"
        declarations.append(f"static {returns} APIENTRY icd_{name[2:]}({signature});")
    ops = ["enum {"] + [f"    ENTGL_OP_{name[2:]} = {i}," for i, name in enumerate(table)] + ["};", ""]
    stubs[2:2] = ops + declarations + [""]
    stubs.append("/* The dispatch table opengl32.dll takes, in its order. */")
    stubs.append("static const PROC entgl_dispatch[336] = {")
    stubs.extend(f"    (PROC)icd_{name[2:]}," for name in table)
    stubs.append("};")
    stubs.append("")
    stubs.append(f"/* {len(by_hand)} functions are written by hand in icd.c: */")
    stubs.extend(f"/*   {name} */" for name in by_hand)
    (HERE / "gl_stubs.inc").write_text("\n".join(stubs) + "\n", newline="\n")

    rust = [
        "// Generated by guest/winxp/opengl/gen.py from icd_table.txt and the SDK's",
        "// GL.h. Do not edit.",
        "",
        "/// The OpenGL 1.1 functions, by opcode: an ICD's dispatch table order.",
        f"pub const NAMES: [&str; {len(table)}] = [",
    ]
    rust.extend(f'    "{name}",' for name in table)
    rust += [
        "];",
        "",
        "/// How many argument words each plainly forwarded opcode carries; `None`",
        "/// for the ones handled elsewhere (or not at all).",
        f"pub const PLAIN_WORDS: [Option<u8>; {len(table)}] = [",
    ]
    plain = {i: words for i, _, words, _ in calls}
    rust.extend(
        f"    {'Some(' + str(plain[i]) + ')' if i in plain else 'None'}," for i in range(len(table))
    )
    rust += [
        "];",
        "",
        "/// Calls the plain OpenGL function `opcode` names with the argument words",
        "/// `a`, whose count the caller has checked against [`PLAIN_WORDS`].",
        "///",
        "/// # Safety",
        "/// An OpenGL context must be current on this thread. Every function here",
        "/// takes numbers only: none reads or writes memory through an argument.",
        "#[allow(clippy::too_many_lines, clippy::cast_possible_wrap, clippy::cast_possible_truncation)]",
        "pub unsafe fn call_plain(gl: &crate::api::Api, opcode: u16, a: &[u32]) {",
        "    // SAFETY: the caller's contract, above; the arguments are plain numbers.",
        "    unsafe {",
        "    match opcode {",
    ]
    for i, name, _, rust_args in calls:
        rust.append(f"        {i} => (gl.{name[2:]})({', '.join(rust_args)}),")
    rust += ["        _ => {}", "    }", "    }", "}", ""]
    rust += ["/// Every function's opcode, by name.", "#[allow(non_upper_case_globals, missing_docs)]", "pub mod op {"]
    rust.extend(f"    pub const {name[2:]}: u16 = {i};" for i, name in enumerate(table))
    rust += ["}", ""]
    rust += [
        "/// The plain functions' signatures, for the table of loaded entry points.",
        "macro_rules! plain_functions {",
        "    ($callback:ident) => {",
        "        $callback! {",
    ]
    for i, name, _, _ in calls:
        types = []
        for kind, _, _ in protos[name][1]:
            types.append(
                "f64" if kind in DOUBLES else "f32" if kind in FLOATS
                else {"GLbyte": "i8", "GLshort": "i16", "GLint": "i32", "GLsizei": "i32",
                      "GLubyte": "u8", "GLushort": "u16", "GLboolean": "u8"}.get(kind, "u32")
            )
        rust.append(f"            {name[2:]}: fn({', '.join(types)});")
    rust += ["        }", "    };", "}", "pub(crate) use plain_functions;", ""]
    target = REPO / "crates" / "gl-passthrough" / "src" / "calls_gen.rs"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(rust), newline="\n")

    print(f"{len(generated)} plain, {len(vectors)} vector forms, {len(by_hand)} by hand")


if __name__ == "__main__":
    main()
