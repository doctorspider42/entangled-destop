"""Writes the placeholder for every device function of the Direct3D 9 DDI.

usage: gen-stubs.py <preprocessed d3dumddi.h> <out.inc>

A driver's device table (D3DDDI_DEVICEFUNCS) has about 140 entries, and the
runtime calls through whichever it likes: an entry left NULL is a crash in
d3d9.dll. So every entry gets a function of the right shape - the shape
matters on x86, where the callee pops its own arguments - that says its name
once (which is how a bring-up learns what a game calls first) and answers
S_OK. entangled_d3d9.c then puts the functions it really has over these.

The shapes are read from the WDK's header and not written down here: the
table grows with every WDDM version. The header is read preprocessed
(build.cmd runs it through the compiler with the interface version the
driver is built for), so the table here is the table the compiler sees.
"""
import re
import sys

header, out = sys.argv[1], sys.argv[2]
text = open(header, encoding='latin-1').read()

# typedef ... HRESULT (APIENTRY *PFND3DDDI_X)(args);  -> how many arguments
shapes = {}
for name, args in re.findall(
        r'\(\s*(?:APIENTRY|__stdcall)\s*\*\s*(PFND3DDDI_\w+)\s*\)\s*\(([^;]*?)\)\s*;', text, re.S):
    shapes[name] = 0 if args.strip() in ('', 'VOID', 'void') else args.count(',') + 1

body = re.search(r'typedef struct _D3DDDI_DEVICEFUNCS\s*\{(.*?)\}\s*D3DDDI_DEVICEFUNCS', text, re.S)
members = re.findall(r'^\s*(PFND3DDDI_\w+)\s+(pfn\w+)\s*;', body.group(1), re.M)
assert len(members) > 100, len(members)

lines = ['/* Generated by gen-stubs.py from d3dumddi.h; do not edit. */', '']
for index, (kind, member) in enumerate(members):
    count = shapes[kind]
    assert 1 <= count <= 12, (kind, count)
    params = ', '.join(['HANDLE device'] + ['void *a%d' % i for i in range(1, count)])
    unused = ' '.join('(void)a%d;' % i for i in range(1, count))
    lines += [
        'static HRESULT APIENTRY',
        'stub_%s(%s)' % (member, params),
        '{',
        '   (void)device; %s' % unused,
        '   return d3d9_stub(%d, "%s");' % (index, member[3:]),
        '}',
        '',
    ]
lines += ['#define D3D9_STUB_COUNT %d' % len(members), '',
          'static void', 'd3d9_fill_stubs(D3DDDI_DEVICEFUNCS *funcs)', '{']
for kind, member in members:
    lines.append('   funcs->%s = (%s)stub_%s;' % (member, kind, member))
lines += ['}', '']
open(out, 'w', encoding='ascii', newline='\n').write('\n'.join(lines))
print('%d device functions' % len(members))
